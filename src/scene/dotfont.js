// Acentos do português: 2 linhas de pontos acima da letra (e a cedilha, 1 linha abaixo).
export const ACCENTS = {
  '́': { above: ['...#.', '..#..'] },   // agudo
  '̀': { above: ['..#..', '...#.'] },   // grave
  '̂': { above: ['..#..', '.#.#.'] },   // circunflexo
  '̃': { above: ['.#.#.', '#.#..'] },   // til
  '̈': { above: ['.#.#.', '.....'] },   // trema
  '̧': { below: ['..#..'] }            // cedilha
};

// 'Ç' -> { base: 'C', marks: [acento] }. Caracteres sem glifo viram espaço.
export function decompose(ch) {
  const [base, ...rest] = [...ch.normalize('NFD')];
  const b = FONT[base] ? base : FONT[base?.toUpperCase()] ? base.toUpperCase() : ' ';
  return { base: b, marks: rest.map((m) => ACCENTS[m]).filter(Boolean) };
}
